import fs from 'node:fs';
// Generate extension/host-config.js from host.config.json, so only one file is hand-written.
const cfg = JSON.parse(fs.readFileSync('host.config.json', 'utf8').replace(/^\uFEFF/, ''));
const body = `// Generated by scripts/setup-extension.mjs from host.config.json. Do not edit.\nexport const HOST_NAME = ${JSON.stringify(cfg.hostName)};\n`;
fs.writeFileSync('extension/host-config.js', body);
console.log('extension/host-config.js ->', cfg.hostName);
